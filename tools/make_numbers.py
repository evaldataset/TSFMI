def dataseed(n: Numbers, root: Path) -> bool:
    f = root / "outputs/dataseed_v2/summary.json"
    if not f.exists():
        return False
    d = load(f)
    src = str(f.relative_to(root))
    for task, rows in d["tasks"].items():
        for row, r in rows.items():
            for seed, v in r["per_data_seed"].items():
                n.put(f"dseed/{task}/{ROW_KEYS[row]}/s{seed}", v, src)
            n.put(f"dseed/{task}/{ROW_KEYS[row]}/range", r["range"], src)
        for k, v in d["claims"][task].items():
            n.put(f"dseed/{task}/claim/{k}", v, src)
        hc = rows["hand_crafted"]["per_data_seed"]
        for m in CANON_MODELS:
            margins = [rows[m]["per_data_seed"][s] - hc[s] for s in hc]
            n.put(f"dseed/{task}/{CANON_MODELS[m]}/minmargin", min(margins), src)
            n.put(f"dseed/{task}/{CANON_MODELS[m]}/maxmargin", max(margins), src)
    return True


