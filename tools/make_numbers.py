def realistic(n: Numbers, root: Path) -> None:
    f = root / "outputs/realistic_anomaly/realistic_anomaly_results.json"
    for r in load(f)["rows"]:
        n.put_ci(
            f"real/{r['baseline'].replace('_', '')}",
            r["test_mean"],
            r["test_ci95_low"],
            r["test_ci95_high"],
            str(f.relative_to(root)),
            r["per_seed_test"],
        )
    old = root / "outputs/realistic_anomaly_tsfm/results.json"  # earlier recipe
    old_rows = [r for r in load(old)["models"] if "test_mean" in r]
    for r in old_rows:
        n.put(
            f"realvone/{CANON_MODELS.get(r['model'], r['model']).replace('_', '')}",
            r["test_mean"],
            str(old.relative_to(root)),
        )

    v2 = root / "outputs/realistic_anomaly_v2"
    cells = {m: v2 / f"{m}_anomaly_realistic" / "canonical_results.json" for m in CANON_MODELS}
    if not all(c.exists() for c in cells.values()):
        for r in old_rows:
            n.put_ci(
                f"real/{CANON_MODELS.get(r['model'], r['model']).replace('_', '')}",
                r["test_mean"],
                r["test_ci95_low"],
                r["test_ci95_high"],
                str(old.relative_to(root)),
            )
        return
    hc = next(r for r in load(f)["rows"] if r["baseline"] == "hand_crafted")["per_seed_test"]
    for m, c in cells.items():
        r = load(c)
        key = CANON_MODELS[m]
        n.put_ci(
            f"real/{key}",
            r["test_mean"],
            r["test_ci95_low"],
            r["test_ci95_high"],
            str(c.relative_to(root)),
            r["test_score_per_seed"],
        )
        # Paired per-seed difference to the hand-crafted baseline (identical splits).
        d = np.array(r["test_score_per_seed"]) - np.array(hc)
        src = f"paired per-seed diff {c.relative_to(root)} - hand_crafted ({f.relative_to(root)})"
        n.put_ci(f"realdiff/{key}", float(d.mean()), 0.0, 0.0, src, list(d))
        n.put(f"realdiff/{key}/p", corrected_t(list(d))[3], src)
        n.put(f"realdiff/{key}/wins", int((d > 0).sum()), src)


def ucr(n: Numbers, root: Path) -> None:
    f = root / "outputs/ucr_tsfm_probe_v2/results.json"
    if not f.exists():
        f = root / "outputs/ucr_tsfm_probe/results.json"
    files = [f]
    ext = root / "outputs/ucr_tsfm_probe_ext/results.json"  # FordA, FordB, Strawberry
    if ext.exists():
        files.append(ext)
    lows = []
    for f, r in ((path, row) for path in files for row in load(path)):
        for k, v in r.items():
            if k != "dataset" and not isinstance(v, (int, float)):
                raise SystemExit(f"{f}: {r['dataset']}/{k} is not a number: {v!r}")
            if k != "dataset":
                n.put(
                    f"ucr/{r['dataset'].lower()}/{k.replace('_', '')}",
                    float(v),
                    str(f.relative_to(root)),
                )
        models = [k for k in r if k not in ("dataset", "hand_crafted", "raw_signal")]
        src = f"count over {len(models)} models in {f.relative_to(root)}"
        ds = r["dataset"].lower()
        n.put(f"ucr/{ds}/nmodels", len(models), src)
        n.put(f"ucr/{ds}/nbelowraw", sum(r[m] < r["raw_signal"] for m in models), src)
        n.put(f"ucr/{ds}/nbelowhc", sum(r[m] < r["hand_crafted"] for m in models), src)
        best_ctrl = max(r["raw_signal"], r["hand_crafted"])
        n.put(f"ucr/{ds}/nabovectrl", sum(r[m] > best_ctrl for m in models), src)
        n.put(f"ucr/{ds}/bestmodel", max(r[m] for m in models), src)
        n.put(f"ucr/{ds}/worstmodel", min(r[m] for m in models), src)
        lows.append(ds)
    n.put("ucr/ndatasets", len(lows), "UCR result files")


