def corrected_t(
    per_seed: list[float], n_train: int = N_TRAIN, n_test: int = N_TEST
) -> tuple[float, float, float, float]:
    """Mean, 95% interval and two-sided p (against 0) of split-seed scores.

    The split seeds reuse the same windows, so their test sets overlap. The variance of the mean is
    inflated with the correction of Nadeau & Bengio (2003): (1/J + n_test/n_train) * s^2, with a
    t distribution on J - 1 degrees of freedom. The p value is meaningful for paired differences.
    """
    from scipy import stats

    x = np.asarray(per_seed, dtype=float)
    x = x[~np.isnan(x)]
    j = len(x)
    mean = float(x.mean())
    var = float(x.var(ddof=1)) * (1.0 / j + n_test / n_train)
    if var == 0.0:
        return mean, mean, mean, 0.0 if mean != 0 else 1.0
    se = var**0.5
    half = float(stats.t.ppf(0.975, j - 1)) * se
    p = float(2 * stats.t.sf(abs(mean) / se, j - 1))
    return mean, mean - half, mean + half, p


class Numbers:
    def __init__(self) -> None:
        self.values: dict[str, str] = {}
        self.sources: dict[str, str] = {}
        self.bootstrap_keys: list[str] = []

    def put(self, key: str, value: float | int | str, source: str, digits: int = 3) -> None:
        if key in self.values:
            raise KeyError(f"duplicate key {key}")
        if isinstance(value, float):
            if value != value:  # NaN: a failed run is not a number to print
                raise ValueError(f"{key} is NaN (from {source})")
            value = f"{value:.{digits}f}"
        self.values[key] = str(value)
        self.sources[key] = source

    def put_ci(
        self,
        prefix: str,
        mean: float,
        lo: float,
        hi: float,
        source: str,
        per_seed: list[float] | None = None,
    ) -> None:
        """Write mean/lo/hi. With per-seed scores, the interval is the corrected t-interval."""
        if per_seed is not None and len(per_seed) > 1:
            mean, lo, hi, _ = corrected_t(per_seed)
        else:
            self.bootstrap_keys.append(prefix)
        # Scores bounded above by 1 (accuracy, ROC-AUC, R^2): the symmetric t-interval is clipped.
        if prefix.split("/")[0] in BOUNDED_NAMESPACES:
            hi = min(hi, 1.0)
            if "seasonality" not in prefix:  # accuracy is also bounded below by 0; R^2 is not
                lo = max(lo, 0.0)
        self.put(f"{prefix}/mean", mean, source)
        self.put(f"{prefix}/lo", lo, source)
        self.put(f"{prefix}/hi", hi, source)

    def tex(self) -> str:
        out = [
            "% Generated by tools/make_numbers.py. Do not edit.",
            "\\makeatletter",
            "\\newcommand{\\val}[1]{\\ifcsname tsfmi@#1\\endcsname\\csname tsfmi@#1\\endcsname"
            "\\else\\PackageError{tsfmi}{Unknown result key '#1'}{Regenerate numbers.tex}\\fi}",
            "\\newcommand{\\ci}[1]{\\val{#1/mean}~[\\val{#1/lo}, \\val{#1/hi}]}",
        ]
        for k in sorted(self.values):
            out.append(f"% {self.sources[k]}")
            out.append(f"\\expandafter\\def\\csname tsfmi@{k}\\endcsname{{{self.values[k]}}}")
        out.append("\\makeatother")
        return "\n".join(out) + "\n"


def load(p: Path) -> object:
    return json.loads(p.read_text())


def _canonical_dir(n: Numbers, root: Path, base: Path, prefix: str) -> None:
    for d in sorted(base.iterdir()):
        f = d / "canonical_results.json"
        if not f.exists():
            continue
        m = re.match(r"(.+?)(?:_pca512|_meanpool)?_(" + "|".join(PROPS) + r")$", d.name)
        if not m or m.group(1) not in CANON_MODELS:
            continue
        r = load(f)
        n.put_ci(
            f"{prefix}/{CANON_MODELS[m.group(1)]}/{m.group(2)}",
            r["test_mean"],
            r["test_ci95_low"],
            r["test_ci95_high"],
            str(f.relative_to(root)),
            r.get("test_score_per_seed", r.get("per_seed_test")),
        )


def canonical(n: Numbers, root: Path, require_v2: bool) -> Path:
    """canon/ = the reported canonical table (v2 when present); canonvone/ = the submitted one."""
    v1, v2 = root / "outputs/canonical", root / "outputs/canonical_v2"
    expected = [
        v2 / f"{m}_{prop}" / "canonical_results.json" for m in CANON_MODELS for prop in PROPS
    ]
    missing = [str(f.parent.name) for f in expected if not f.exists()]
    has_v2 = not missing
    if require_v2 and not has_v2:
        raise SystemExit(f"canonical_v2 incomplete ({len(missing)} cells missing): {missing[:6]}")
    if not has_v2:
        print(
            f"note: canonical_v2 incomplete ({len(missing)}/{len(expected)} missing); "
            "using the submitted table for canon/"
        )
    _canonical_dir(n, root, v1, "canonvone")
    base = v2 if has_v2 else v1
    _canonical_dir(n, root, base, "canon")
    return base


