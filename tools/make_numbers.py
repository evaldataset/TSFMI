def strongest_control(n: Numbers, root: Path) -> bool:
    """Per task: the strongest non-model control, the best model, and their margin."""
    sx_f = root / "outputs/strong_controls_ext/results.json"
    if not sx_f.exists():
        return False
    sx = load(sx_f)
    src = (
        "strongest non-model control vs best model (outputs/canonical_v2, strong_controls_ext, ...)"
    )
    names = {
        "raw_signal": "raw signal",
        "hand_crafted": "hand-crafted",
        "random_projection": "random projection",
        "rocket": "ROCKET-style",
        "tsfresh_minimal": "tsfresh (minimal)",
        "tsfresh_efficient": "tsfresh (efficient)",
        "max_abs_only": "max|x|",
    }

    def put(prefix: str, ctrls: dict[str, float], models: dict[str, float]) -> float:
        bc = max(ctrls, key=ctrls.get)
        bm = max(models, key=models.get)
        margin = models[bm] - ctrls[bc]
        n.put(f"{prefix}/bestctrl", names.get(bc, bc), src)
        n.put(f"{prefix}/bestctrlval", ctrls[bc], src)
        n.put(f"{prefix}/bestmodel", MODEL_NAMES[bm], src)
        n.put(f"{prefix}/bestmodelval", models[bm], src)
        n.put(f"{prefix}/margin", margin, src)
        n.put(f"{prefix}/nabove", sum(v > ctrls[bc] for v in models.values()), src)
        return margin

    # canonical: raw, HC, RP, tsfresh (+ ROCKET where run, + max|x| for anomaly)
    base = {
        (r["baseline"], r["property"]): r["test_mean"]
        for r in load(root / "outputs/canonical_v2/baselines/all_results.json")
    }
    rocket = {
        r["dataset"]: r["test_mean"]
        for r in load(root / "outputs/rocket_baselines/rocket_results.json")
    }
    maxabs = next(
        r["test_mean"]
        for r in load(root / "outputs/per_feature_anomaly/per_feature_results.json")
        if r["subset"] == "max_abs_only"
    )
    margins = []
    for prop in PROPS:
        ctrls = {b: base[(b, prop)] for b in ("raw_signal", "hand_crafted", "random_projection")}
        for k, v in sx.get("canonical", {}).get(prop, {}).items():
            ctrls[k] = float(np.mean(v["per_seed"]))
        if prop in rocket:
            ctrls["rocket"] = rocket[prop]
        if prop == "anomaly":
            ctrls["max_abs_only"] = maxabs
        models = {}
        for m in CANON_MODELS:
            f = root / f"outputs/canonical_v2/{m}_{prop}/canonical_results.json"
            models[m] = load(f)["test_mean"]
        margins.append(put(f"sc/canon/{prop}", ctrls, models))
    n.put("sc/canon/nctrlatleast", sum(m <= 0 for m in margins), src)
    n.put("sc/canon/maxmargin", max(margins), src)

    # realistic, per data seed (models from canonical v2 / dataseed v2)
    ds = load(root / "outputs/dataseed_v2/summary.json")["tasks"]["realistic"]
    rmargins = []
    for seed, ctrl_rows in sx["realistic"].items():
        ctrls = {k: float(np.mean(v["per_seed"])) for k, v in ctrl_rows.items()}
        models = {m: ds[m]["per_data_seed"][seed] for m in CANON_MODELS}
        rmargins.append(put(f"sc/real/{seed}", ctrls, models))
    n.put("sc/real/maxmargin", max(rmargins), src)
    n.put("sc/real/minmargin", min(rmargins), src)
    n.put("sc/real/ctrlleadmin", -max(rmargins), src)  # strongest control's lead over best model
    n.put("sc/real/ctrlleadmax", -min(rmargins), src)

    # UCR: controls on the same resized input, models from the UCR probe files
    rows = load(root / "outputs/ucr_tsfm_probe_v2/results.json") + load(
        root / "outputs/ucr_tsfm_probe_ext/results.json"
    )
    umargins, upos = [], 0
    for r in rows:
        c = sx["ucr"][r["dataset"]]
        ctrls = {
            k: c[k]
            for k in (
                "raw_signal",
                "hand_crafted",
                "rocket",
                "tsfresh_minimal",
                "tsfresh_efficient",
            )
        }
        models = {m: r[m] for m in CANON_MODELS}
        mg = put(f"sc/ucr/{r['dataset'].lower()}", ctrls, models)
        umargins.append(mg)
        upos += mg > 0
    n.put("sc/ucr/ndatasets", len(rows), src)
    n.put("sc/ucr/nmodelwins", upos, src)
    n.put("sc/ucr/nctrlwins", len(rows) - upos, src)
    n.put(
        "sc/ucr/nrocketwins",
        sum(sx["ucr"][r["dataset"]]["rocket"] >= max(r[m] for m in CANON_MODELS) for r in rows),
        src,
    )
    n.put("sc/ucr/maxmargin", max(umargins), src)
    n.strongest_margins = margins + rmargins + umargins  # hard margins are added in hard_variants
    return True


def paired_strongest(n: Numbers, root: Path) -> bool:
    """Per-setting paired test of best model vs strongest control in the 14 synthetic settings.

    Best model and strongest control are the ones with the highest mean test score (as in the
    summary table, a descriptive choice). Their per-split-seed scores share splits, so the paired
    difference gets the corrected resampled-t interval and p value. UCR settings are single runs
    and get no interval.
    """
    base = {
        (r["baseline"], r["property"]): r["per_seed_test"]
        for r in load(root / "outputs/canonical_v2/baselines/all_results.json")
    }
    hbase = {
        (r["baseline"], r["property"]): r["per_seed_test"]
        for r in load(root / "outputs/hard_variants_v2/baselines/all_results.json")
    }
    rocket = {
        r["dataset"]: r["per_seed_test"]
        for r in load(root / "outputs/rocket_baselines/rocket_results.json")
    }
    maxabs = next(
        r["per_seed_test"]
        for r in load(root / "outputs/per_feature_anomaly/per_feature_results.json")
        if r["subset"] == "max_abs_only"
    )
    sx = load(root / "outputs/strong_controls_ext/results.json")

    def cell(path: Path) -> list[float]:
        return load(path / "canonical_results.json")["test_score_per_seed"]

    settings: dict[str, tuple[dict, dict]] = {}
    for prop in PROPS:
        ctrls = {b: base[(b, prop)] for b in ("raw_signal", "hand_crafted", "random_projection")}
        for k, v in sx["canonical"][prop].items():
            ctrls[k] = v["per_seed"]
        if prop in rocket:
            ctrls["rocket"] = rocket[prop]
        if prop == "anomaly":
            ctrls["max_abs_only"] = maxabs
        models = {m: cell(root / f"outputs/canonical_v2/{m}_{prop}") for m in CANON_MODELS}
        settings[f"canon/{prop}"] = (models, ctrls)
    for h in HARD:
        ctrls = {b: hbase[(b, h)] for b in ("raw_signal", "hand_crafted", "random_projection")}
        for k in ("tsfresh_minimal", "tsfresh_efficient"):
            ctrls[k] = sx["hard"][h][k]["per_seed"]
        ctrls["rocket"] = rocket[h]
        models = {m: cell(root / f"outputs/hard_variants_v2/{m}_{h}") for m in CANON_MODELS}
        settings[f"hard/{h}"] = (models, ctrls)
    for seed, rows in sx["realistic"].items():
        ctrls = {k: v["per_seed"] for k, v in rows.items()}
        mdir = (
            (root / "outputs/realistic_anomaly_v2")
            if seed == "42"
            else (root / f"outputs/dataseed_v2/seed{seed}")
        )
        models = {m: cell(mdir / f"{m}_anomaly_realistic") for m in CANON_MODELS}
        settings[f"real/{seed}"] = (models, ctrls)
    src = "paired per-seed difference, best model - strongest control (corrected resampled t)"
    n_ci0 = n_ctrl = n_model = 0
    for key, (models, ctrls) in settings.items():
        bm = max(models, key=lambda m: np.mean(models[m]))
        bc = max(ctrls, key=lambda c: np.mean(ctrls[c]))
        d = list(np.asarray(models[bm]) - np.asarray(ctrls[bc]))
        mean, lo, hi, pval = corrected_t(d)
        n.put(f"sc/{key}/pdiff/mean", mean, src)
        n.put(f"sc/{key}/pdiff/lo", lo, src)
        n.put(f"sc/{key}/pdiff/hi", hi, src)
        n.put(f"sc/{key}/pdiff/p", "$<$0.001" if pval < 1e-3 else f"{pval:.3f}", src)
        if lo <= 0 <= hi:
            n_ci0 += 1
        elif hi < 0:
            n_ctrl += 1
        else:
            n_model += 1
    n.put("sc/syn/nsettings", len(settings), src)
    n.put(
        "sc/syn/nexact",
        sum(
            np.allclose(
                models[max(models, key=lambda m: np.mean(models[m]))],
                ctrls[max(ctrls, key=lambda c: np.mean(ctrls[c]))],
            )
            for models, ctrls in settings.values()
        ),
        src,
    )
    n.put("sc/syn/nci0", n_ci0, src)
    n.put("sc/syn/nctrlsig", n_ctrl, src)
    n.put("sc/syn/nmodelsig", n_model, src)
    return True


