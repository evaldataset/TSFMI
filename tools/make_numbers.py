def selectivity_range(n: Numbers, root: Path) -> None:
    """Per k and property: the model range of selectivity and where the HC control falls in it."""
    f = root / "outputs/hl_selectivity_v2/results.json"
    src = f"{f.relative_to(root)} (model min/max; hand_crafted at n=1000)"
    table: dict[tuple[int, str], dict[str, float]] = {}
    for r in load(f)["results"]:
        if "selectivity" not in r or (r["row_kind"] != "model" and r["num_samples"] != 1000):
            continue
        table.setdefault((r["k"], r["property"]), {})[r["row"]] = r["selectivity"]["mean"]
    for (k, prop), rows in sorted(table.items()):
        models = [rows[m] for m in CANON_MODELS]
        hc = rows["hand_crafted"]
        n.put(f"selk/{k}/{prop}/min", min(models), src)
        n.put(f"selk/{k}/{prop}/max", max(models), src)
        n.put(f"selk/{k}/{prop}/hc", hc, src)
        n.put(f"selk/{k}/{prop}/hcrank", 1 + sum(v > hc for v in models), src)


