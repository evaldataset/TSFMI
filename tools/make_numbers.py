    rocket_dims = {v["rocket"]["dim"] for v in d.get("realistic", {}).values()}
    if len(rocket_dims) == 1:
        n.put("sx/rocketdim", f"{rocket_dims.pop():,}".replace(",", "{,}"), src)
    return True


