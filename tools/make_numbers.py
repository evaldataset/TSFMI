def layer_selection(n: Numbers, root: Path, n_layers: dict[str, int]) -> None:
    """Depth of the validation-selected layer: how often the first block already wins."""
    src = "outputs/canonical_v2/*/canonical_results.json (best_layer_per_seed)"
    for prop in PROPS:
        first, total, depths = 0, 0, []
        for m, key in CANON_MODELS.items():
            cands = list(
                (root / "outputs/canonical_v2").glob(f"{m}*_{prop}/canonical_results.json")
            )
            cands = [
                c for c in cands if re.match(rf"{m}(_pca512|_meanpool)?_{prop}$", c.parent.name)
            ]
            if len(cands) != 1:
                raise ValueError(f"expected one canonical_v2 dir for {m}/{prop}, got {cands}")
            idx = [
                int(re.search(r"(\d+)$", s).group(1)) for s in load(cands[0])["best_layer_per_seed"]
            ]
            first += sum(i == 0 for i in idx)
            total += len(idx)
            rel = [i / (n_layers[m] - 1) for i in idx]
            depths.extend(rel)
            n.put(f"layer/{key}/{prop}/depth", float(np.mean(rel)), src, digits=2)
        n.put(f"layer/{prop}/nfirst", first, src)
