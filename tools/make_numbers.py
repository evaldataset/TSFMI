def strongest_control(n: Numbers, root: Path) -> bool:
    """Per task: the strongest non-model control, the best model, and their margin."""
    sx_f = root / "outputs/strong_controls_ext/results.json"
    if not sx_f.exists():
        return False
    sx = load(sx_f)
    src = (
        "strongest non-model control vs best model (outputs/canonical_v2, strong_controls_ext, ...)"
    )
    names = {
        "raw_signal": "raw signal",
        "hand_crafted": "hand-crafted",
        "random_projection": "random projection",
        "rocket": "ROCKET-style",
        "tsfresh_minimal": "tsfresh (minimal)",
        "tsfresh_efficient": "tsfresh (efficient)",
        "max_abs_only": "max|x|",
    }

    def put(prefix: str, ctrls: dict[str, float], models: dict[str, float]) -> float:
        bc = max(ctrls, key=ctrls.get)
        bm = max(models, key=models.get)
        margin = models[bm] - ctrls[bc]
        n.put(f"{prefix}/bestctrl", names.get(bc, bc), src)
        n.put(f"{prefix}/bestctrlval", ctrls[bc], src)
        n.put(f"{prefix}/bestmodel", MODEL_NAMES[bm], src)
        n.put(f"{prefix}/bestmodelval", models[bm], src)
        n.put(f"{prefix}/margin", margin, src)
        n.put(f"{prefix}/nabove", sum(v > ctrls[bc] for v in models.values()), src)
        return margin

    # canonical: raw, HC, RP, tsfresh (+ ROCKET where run, + max|x| for anomaly)
    base = {
        (r["baseline"], r["property"]): r["test_mean"]
        for r in load(root / "outputs/canonical_v2/baselines/all_results.json")
    }
    rocket = {
        r["dataset"]: r["test_mean"]
        for r in load(root / "outputs/rocket_baselines/rocket_results.json")
    }
    maxabs = next(
        r["test_mean"]
        for r in load(root / "outputs/per_feature_anomaly/per_feature_results.json")
        if r["subset"] == "max_abs_only"
    )
    margins = []
    for prop in PROPS:
        ctrls = {b: base[(b, prop)] for b in ("raw_signal", "hand_crafted", "random_projection")}
        for k, v in sx.get("canonical", {}).get(prop, {}).items():
            ctrls[k] = float(np.mean(v["per_seed"]))
        if prop in rocket:
            ctrls["rocket"] = rocket[prop]
        if prop == "anomaly":
            ctrls["max_abs_only"] = maxabs
        models = {}
        for m in CANON_MODELS:
            f = root / f"outputs/canonical_v2/{m}_{prop}/canonical_results.json"
            models[m] = load(f)["test_mean"]
        margins.append(put(f"sc/canon/{prop}", ctrls, models))
    n.put("sc/canon/nctrlatleast", sum(m <= 0 for m in margins), src)
    n.put("sc/canon/maxmargin", max(margins), src)

    # realistic, per data seed (models from canonical v2 / dataseed v2)
    ds = load(root / "outputs/dataseed_v2/summary.json")["tasks"]["realistic"]
    rmargins = []
    for seed, ctrl_rows in sx["realistic"].items():
        ctrls = {k: float(np.mean(v["per_seed"])) for k, v in ctrl_rows.items()}
        models = {m: ds[m]["per_data_seed"][seed] for m in CANON_MODELS}
        rmargins.append(put(f"sc/real/{seed}", ctrls, models))
    n.put("sc/real/maxmargin", max(rmargins), src)
    n.put("sc/real/minmargin", min(rmargins), src)
    n.put("sc/real/ctrlleadmin", -max(rmargins), src)  # strongest control's lead over best model
    n.put("sc/real/ctrlleadmax", -min(rmargins), src)

    # UCR: controls on the same resized input, models from the UCR probe files
    rows = load(root / "outputs/ucr_tsfm_probe_v2/results.json") + load(
        root / "outputs/ucr_tsfm_probe_ext/results.json"
    )
    umargins, upos = [], 0
    for r in rows:
        c = sx["ucr"][r["dataset"]]
        ctrls = {
            k: c[k]
            for k in (
                "raw_signal",
                "hand_crafted",
                "rocket",
                "tsfresh_minimal",
                "tsfresh_efficient",
            )
        }
        models = {m: r[m] for m in CANON_MODELS}
        mg = put(f"sc/ucr/{r['dataset'].lower()}", ctrls, models)
        umargins.append(mg)
        upos += mg > 0
    n.put("sc/ucr/ndatasets", len(rows), src)
    n.put("sc/ucr/nmodelwins", upos, src)
    n.put("sc/ucr/nctrlwins", len(rows) - upos, src)
    n.put(
        "sc/ucr/nrocketwins",
        sum(sx["ucr"][r["dataset"]]["rocket"] >= max(r[m] for m in CANON_MODELS) for r in rows),
        src,
    )
    n.put("sc/ucr/maxmargin", max(umargins), src)
    n.strongest_margins = margins + rmargins + umargins  # hard margins are added in hard_variants
    return True


def hard_variants(n: Numbers, root: Path) -> bool:
    base = root / "outputs/hard_variants_v2"
    cells = {
        (m, h): base / f"{m}_{h}" / "canonical_results.json" for m in CANON_MODELS for h in HARD
    }
    if not all(c.exists() for c in cells.values()):
        return False
    for (m, h), c in cells.items():
        r = load(c)
        n.put_ci(
            f"hard/{CANON_MODELS[m]}/{h}",
            r["test_mean"],
            r["test_ci95_low"],
            r["test_ci95_high"],
            str(c.relative_to(root)),
            r["test_score_per_seed"],
        )
    f = base / "baselines/all_results.json"
    ctrl: dict[str, dict[str, float]] = {}
    for r in load(f):
        n.put_ci(
            f"hardbase/{r['baseline']}/{r['property']}",
            r["test_mean"],
            r["test_ci95_low"],
            r["test_ci95_high"],
            str(f.relative_to(root)),
            r["per_seed_test"],
        )
        ctrl.setdefault(r["property"], {})[r["baseline"]] = r["test_mean"]
    rocket = {
        r["dataset"]: r["test_mean"]
        for r in load(root / "outputs/rocket_baselines/rocket_results.json")
    }
    src = "hard_variants_v2 cells vs hard baselines and rocket_baselines"
    margins = []
    sx_f = root / "outputs/strong_controls_ext/results.json"
    sx_hard = load(sx_f).get("hard", {}) if sx_f.exists() else {}
    for h in HARD:
        ctrl[h]["rocket"] = rocket[h]
        for k in ("tsfresh_minimal", "tsfresh_efficient"):
            if k in sx_hard.get(h, {}):
                ctrl[h][k] = sx_hard[h][k]["mean"]
        best = max(ctrl[h], key=ctrl[h].get)
        models = {m: load(cells[(m, h)])["test_mean"] for m in CANON_MODELS}
        above = sorted(m for m, v in models.items() if v > ctrl[h][best])
        label = {
            "rocket": "ROCKET-style",
            "tsfresh_minimal": "tsfresh (minimal)",
            "tsfresh_efficient": "tsfresh (efficient)",
            "hand_crafted": "hand-crafted",
            "raw_signal": "raw signal",
        }.get(best, best.replace("_", " "))
        n.put(f"hardcmp/{h}/bestctrl", label, src)
        n.put(f"hardcmp/{h}/bestctrlval", ctrl[h][best], src)
        n.put(f"hardcmp/{h}/nabovectrl", len(above), src)
        n.put(
            f"hardcmp/{h}/nbelowraw", sum(v < ctrl[h]["raw_signal"] for v in models.values()), src
        )
        n.put(f"hardcmp/{h}/nabovepointnine", sum(v > 0.9 for v in models.values()), src)
        n.put(f"hardcmp/{h}/nmodels", len(models), src)
        margin = max(v - ctrl[h][best] for v in models.values())
        margins.append(margin)
        n.put(f"hardcmp/{h}/maxmargin", margin, src)
    n.put("hardcmp/maxmargin", max(margins), src)
    n.put("hardcmp/npositive", sum(m > 0 for m in margins), src)
    allm = getattr(n, "strongest_margins", []) + margins
    if allm:
        s2 = "all task settings: canonical (6), hard (5), realistic data seeds (3), UCR (6)"
        n.put("sc/all/nsettings", len(allm), s2)
        n.put("sc/all/npositive", sum(m > 0 for m in allm), s2)
        n.put("sc/all/maxmargin", max(allm), s2)
        n.put("sc/all/nabovetie", sum(round(m, 3) > 0.01 for m in allm), s2)
    return True


def wilinski(n: Numbers, root: Path) -> None:
    f = root / "outputs/wilinski_moment_ldr/results.json"
    d = load(f)
    src = str(f.relative_to(root))
    pairs = {
        "constant_vs_sine": "constsine",
        "increasing_vs_decreasing": "incdec",
        "high_vs_low_freq": "highlow",
    }
    for pair, key in pairs.items():
        for size in ("n20", "n512"):
            c = d["pairs"][pair][size]
            for space in ("raw_signal", "hand_crafted"):
                for clf in ("lda", "diffmean"):
                    n.put(
                        f"wil/{key}/{size}/{space.replace('_', '')}/{clf}",
                        c["controls"][space][f"{clf}_heldout_acc"],
                        src,
                        digits=2,
                    )
            m = c["moment"]
            for clf in ("lda", "diffmean"):
                vals = [
                    m[f"train_dropout_seed{s}"]["summary"][f"best_pooled_layer_{clf}_heldout_acc"][
                        "value"
                    ]
                    for s in range(3)
                ]
                n.put(f"wil/{key}/{size}/moment/{clf}", min(vals), src, digits=2)
    n.put("wil/commit", d["wilinski_commit"][:7], src)
    # Dropout sensitivity of the published layer-wise picture (constant vs sine, n = 20).
    m = d["pairs"]["constant_vs_sine"]["n20"]["moment"]
    drop = [m[f"train_dropout_seed{s}"]["summary"] for s in range(3)]
    ldr = [x["best_pooled_layer_ldr"]["value"] for x in drop]
    peaks = [x["pooled_scaled_argmax_layer"] for x in drop]
    n.put("wil/cs20/drop/ldrmin", f"{min(ldr):.0f}", src)
    n.put("wil/cs20/drop/ldrmax", f"{max(ldr):.0f}", src)
    n.put("wil/cs20/drop/peakmin", min(peaks), src)
    n.put("wil/cs20/drop/peakmax", max(peaks), src)
    ev = m["eval"]["summary"]
    exp = int(np.floor(np.log10(ev["best_pooled_layer_ldr"]["value"])))
    n.put("wil/cs20/eval/ldrexp", exp, src)
    n.put("wil/cs20/eval/peak", ev["pooled_scaled_argmax_layer"], src)


