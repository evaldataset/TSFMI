def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tsfmi", type=Path, default=Path("."), help="TSFMI repository root")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--require-canonical-v2", action="store_true")
    args = ap.parse_args()
    root = args.tsfmi.resolve()

    n = Numbers()
    base = canonical(n, root, args.require_canonical_v2)
    baselines(n, root, base)
    per_feature(n, root)
    bayes(n, root)
    realistic(n, root)
    ucr(n, root)
    selectivity(n, root)
    selectivity_range(n, root)
    recoverability(n, root)
    mechanism(n, root)
    patchtst(n, root)
    task_facts(n, root)
    wilinski(n, root)
    environment(n, root)
    strong_baselines(n, root)
    layer_selection(n, root, storage(n, root))
    if not throughput(n, root):
        print("note: extraction_throughput missing; tp/ keys not written")
    negative_control(n, root)
    for fn, what in (
        (multicapacity, "capacity_probe_v2"),
        (strong_controls_ext, "strong_controls_ext"),
        (strongest_control, "strongest-control summary"),
        (anomaly_diagnostics, "anomaly_diagnostics"),
        (erasure, "statistic_erasure"),
        (dataseed, "dataseed_v2/summary.json"),
        (view_sensitivity, "view_sensitivity"),
        (view_shift, "view shift"),
        (fix_changes, "fix_2026_10"),
    ):
        if not fn(n, root):
            print(f"note: {what} missing; its keys not written")
    if not hard_variants(n, root):
        print("note: hard_variants_v2 incomplete; hard/ keys not written")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(n.tex())
    if n.bootstrap_keys:
        print(
            f"note: {len(n.bootstrap_keys)} intervals without per-seed scores (source interval "
            f"kept): {', '.join(sorted(set(k.split('/')[0] for k in n.bootstrap_keys)))}"
        )
    print(f"{len(n.values)} values from canonical source {base.relative_to(root)} -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
