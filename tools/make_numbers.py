def multicapacity(n: Numbers, root: Path) -> bool:
    """Capacity sweep (canonical v2 protocol, per-probe validation-selected layer, 7 models)."""
    f = root / "outputs/capacity_probe_v2/results.json"
    if not f.exists():
        return False
    d = load(f)
    src = str(f.relative_to(root))
    for task, rows in d["results"].items():
        gains = []
        for row, probes in rows.items():
            key = ROW_KEYS[row]
            for probe, v in probes.items():
                n.put_ci(
                    f"cap/{task}/{key}/{probe.replace('_', '')}",
                    v["mean"],
                    v["ci95"][0],
                    v["ci95"][1],
                    src,
                    v["per_seed"],
                )
            if row in CANON_MODELS:
                lin = probes["linear"]["mean"]
                best_p = max((p for p in probes if p != "linear"), key=lambda p: probes[p]["mean"])
                gains.append((probes[best_p]["mean"] - lin, row, best_p))
        models = {r: p for r, p in rows.items() if r in CANON_MODELS}
        best = max(
            ((r, p, v["mean"]) for r, ps in models.items() for p, v in ps.items()),
            key=lambda t: t[2],
        )
        n.put(f"cap/{task}/best", best[2], src)
        n.put(f"cap/{task}/bestmodel", MODEL_NAMES[best[0]], src)
        n.put(f"cap/{task}/bestprobe", best[1].replace("_", " "), src)
        g, m, probe = max(gains)
        n.put(f"cap/{task}/maxgain", g, src)
        n.put(f"cap/{task}/maxgainmodel", MODEL_NAMES[m], src)
        n.put(f"cap/{task}/maxgainprobe", probe.replace("_", " "), src)
        n.put(f"cap/{task}/hcbest", max(v["mean"] for v in rows["hand_crafted"].values()), src)
        n.put(f"cap/{task}/nconfigs", sum(len(p) for p in models.values()), src)
    return True


def _ctl(k: str) -> str:
    return k.replace("_", "").replace("tsfresh", "ts")


def strong_controls_ext(n: Numbers, root: Path) -> bool:
    """ROCKET-style / tsfresh on realistic (3 data seeds), hard, UCR and canonical (per seed)."""
    f = root / "outputs/strong_controls_ext/results.json"
