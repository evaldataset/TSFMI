def anomaly_diagnostics(n: Numbers, root: Path) -> bool:
    """Per-type recall on the realistic generator and label-efficiency curves."""
    f = root / "outputs/anomaly_diagnostics/results.json"
    if not f.exists():
        return False
    d = load(f)
    src = str(f.relative_to(root))
    for row, r in d["per_type_realistic"].items():
        key = ROW_KEYS[row]
        n.put(f"ptype/{key}/acc", r["accuracy_mean"], src)
        for kind, v in r["recall"].items():
            n.put(f"ptype/{key}/{kind.replace('_', '')}", v, src, digits=2)
    ref = {
        m: load(
            root / f"outputs/realistic_anomaly_v2/{m}_anomaly_realistic/canonical_results.json"
        )["test_mean"]
        for m in CANON_MODELS
    }
    dev = max(abs(d["per_type_realistic"][m]["accuracy_mean"] - ref[m]) for m in CANON_MODELS)
    n.put("ptype/maxdev", dev, f"{src} vs outputs/realistic_anomaly_v2 (refit consistency)")
    ctx = [r["recall"]["contextual"] for r in d["per_type_realistic"].values()]
    n.put("ptype/contextual/min", min(ctx), src, digits=2)
    n.put("ptype/contextual/max", max(ctx), src, digits=2)
    for kind in ("variance", "normal"):
        best = max(
            d["per_type_realistic"], key=lambda r: d["per_type_realistic"][r]["recall"][kind]
        )
        n.put(f"ptype/best/{kind}", best, src)
    for kind, cnt in next(iter(d["per_type_realistic"].values()))["counts"].items():
        n.put(f"ptype/count/{kind.replace('_', '')}", cnt, src)
    for task, rows in d["learning_curve"].items():
        hc = rows["hand_crafted"]
        sizes = [str(x) for x in d["train_sizes"]]
        n.put(f"curve/{task}/sizes/min", sizes[0], src)
        n.put(f"curve/{task}/sizes/max", sizes[-1], src)
        n.put(
            f"curve/{task}/bestmodelatmax",
            max(rows[m][sizes[-1]]["mean"] for m in CANON_MODELS),
            src,
        )
        for m in CANON_MODELS:
            above = [z for z in sizes if rows[m][z]["mean"] > hc[z]["mean"]]
            n.put(f"curve/{task}/{CANON_MODELS[m]}/nabovehc", len(above), src)
            n.put(
                f"curve/{task}/{CANON_MODELS[m]}/firstabovehc", above[0] if above else "none", src
            )
        for row, curve in rows.items():
            for size, v in curve.items():
                n.put_ci(
                    f"curve/{task}/{ROW_KEYS[row]}/{size}",
                    v["mean"],
                    v["ci95"][0],
                    v["ci95"][1],
                    src,
                    v["per_seed"],
                )
    return True


